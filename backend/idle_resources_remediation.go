// JiraIssueRequest is a normalized payload for creating a Jira cloud issue.
// The remediation handler builds one from the selected resources.
type JiraIssueRequest struct {
	Summary     string
	Description string
	IssueType   string
}

// createJiraIssue creates a single issue in Jira Cloud using the v3 REST API.
// Returns the issue key (e.g. "DEVOPS-1234") and a browse URL.
func createJiraIssue(ctx context.Context, req JiraIssueRequest) (key, url string, err error) {
	if JiraURL == "" || JiraEmail == "" || JiraToken == "" || JiraProject == "" {
		return "", "", fmt.Errorf("jira is not configured (set JIRA_URL, JIRA_EMAIL, JIRA_TOKEN, JIRA_PROJECT)")
	}
	if req.IssueType == "" {
		req.IssueType = "Task"
	}
	endpoint := strings.TrimRight(JiraURL, "/") + "/rest/api/3/issue"
	payload := map[string]any{
		"fields": map[string]any{
			"project":   map[string]string{"key": JiraProject},
			"summary":   req.Summary,
			"issuetype": map[string]string{"name": req.IssueType},
			"description": map[string]any{
				"type":    "doc",
				"version": 1,
				"content": []map[string]any{{
					"type": "paragraph",
					"content": []map[string]any{{
						"type": "text",
						"text": req.Description,
					}},
				}},
			},
		},
	}
	body, _ := json.Marshal(payload)
	httpReq, err := http.NewRequestWithContext(ctx, "POST", endpoint, bytes.NewReader(body))
	if err != nil {
		return "", "", err
	}
	httpReq.SetBasicAuth(JiraEmail, JiraToken)
	httpReq.Header.Set("Content-Type", "application/json")
	httpReq.Header.Set("Accept", "application/json")
	resp, err := http.DefaultClient.Do(httpReq)
	if err != nil {
		return "", "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 300 {
		buf := new(bytes.Buffer)
		_, _ = buf.ReadFrom(resp.Body)
		return "", "", fmt.Errorf("jira responded %d: %s", resp.StatusCode, strings.TrimSpace(buf.String()))
	}
	var parsed struct {
		Key  string `json:"key"`
		Self string `json:"self"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&parsed); err != nil {
		return "", "", err
	}
	browse := strings.TrimRight(JiraURL, "/") + "/browse/" + parsed.Key
	return parsed.Key, browse, nil
}

// buildJiraDescription crafts a human-readable summary of the resources to
// remove. It pairs nicely with a `cleanup.tf` link in the description.
func buildJiraDescription(scan *IdleScan, resources []IdleResource, cleanupURL, prURL string) string {
	var b strings.Builder
	totalCost := 0.0
	for _, r := range resources {
		totalCost += r.CostEstimateUSD
	}
	fmt.Fprintf(&b, "Idle resources detected by Scan #%d on %s.\n\n", scan.ID, scan.Cloud)
	fmt.Fprintf(&b, "Estimated monthly savings: $%.2f\n", totalCost)
	fmt.Fprintf(&b, "Resources to remove (%d):\n\n", len(resources))
	for _, r := range resources {
		fmt.Fprintf(&b, "- %s/%s · %s · region=%s · severity=%s · $%.2f/mo · %s\n",
			r.Cloud, r.Service, oneLine(safeNonEmpty(r.Name, r.ResourceID)), r.Region, r.Severity, r.CostEstimateUSD, r.Reason)
	}
	if cleanupURL != "" {
		fmt.Fprintf(&b, "\ncleanup.tf: %s\n", cleanupURL)
	}
	if prURL != "" {
		fmt.Fprintf(&b, "Pull request: %s\n", prURL)
	}
	return b.String()
}

// ---------- helpers ----------

func safeNonEmpty(primary, fallback string) string {
	if strings.TrimSpace(primary) != "" {
		return primary
	}
	return fallback
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	return strings.TrimSpace(s)
}
