#!/bin/bash
# Sync environment variables from config/.env to root .env for docker-compose
# This is needed because docker-compose variable substitution reads from .env in the compose directory

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
CONFIG_ENV="$PROJECT_ROOT/config/.env"
ROOT_ENV="$PROJECT_ROOT/.env"

if [ ! -f "$CONFIG_ENV" ]; then
    echo "Error: $CONFIG_ENV does not exist"
    echo "Please create it by copying config/.env.example"
    exit 1
fi

echo "Syncing environment variables from config/.env to .env for docker-compose..."

# Extract variables from config/.env and write to root .env
cat > "$ROOT_ENV" << 'EOF'
# Docker Compose environment variable substitution
# This file is auto-generated by scripts/sync-env.sh
# Do not edit manually - edit config/.env instead
#
# This file is used by docker-compose for ${VARIABLE} substitution.
# Keep it in sync with config/.env so compose services do not fall back to insecure defaults.

EOF

# Read config/.env and extract variable assignments (skip comments and empty lines)
while IFS= read -r line || [ -n "$line" ]; do
    # Skip comments and empty lines
    if [[ "$line" =~ ^[[:space:]]*# ]] || [[ -z "${line// }" ]]; then
        continue
    fi
    
    # Extract variable name and value
    if [[ "$line" =~ ^([A-Z_]+)=(.*)$ ]]; then
        var_name="${BASH_REMATCH[1]}"
        var_value="${BASH_REMATCH[2]}"
        
        echo "$var_name=$var_value" >> "$ROOT_ENV"
    fi
done < "$CONFIG_ENV"

# Mirror DB_* into POSTGRES_* for docker-compose postgres service when explicit
# POSTGRES_* values are not present in config/.env. This keeps backend and
# postgres aligned from a single source of truth.
db_user="$(grep -E '^DB_USER=' "$ROOT_ENV" | tail -n1 | cut -d'=' -f2-)"
db_password="$(grep -E '^DB_PASSWORD=' "$ROOT_ENV" | tail -n1 | cut -d'=' -f2-)"
db_name="$(grep -E '^DB_NAME=' "$ROOT_ENV" | tail -n1 | cut -d'=' -f2-)"

if ! grep -q '^POSTGRES_USER=' "$ROOT_ENV" && [ -n "$db_user" ]; then
    echo "POSTGRES_USER=$db_user" >> "$ROOT_ENV"
fi
if ! grep -q '^POSTGRES_PASSWORD=' "$ROOT_ENV" && [ -n "$db_password" ]; then
    echo "POSTGRES_PASSWORD=$db_password" >> "$ROOT_ENV"
fi
if ! grep -q '^POSTGRES_DB=' "$ROOT_ENV" && [ -n "$db_name" ]; then
    echo "POSTGRES_DB=$db_name" >> "$ROOT_ENV"
fi

echo "✓ Synced environment variables to $ROOT_ENV"
echo ""
echo "You can now run: docker-compose up -d"
